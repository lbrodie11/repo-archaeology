#!/usr/bin/env node
/**
 * Browser build of the shared plate layout engine (`scripts/build-plate-layout.mjs`).
 *
 * `src/map/plate-layout.ts` is the single implementation of the Briefing blueprint plate layout.
 * The server imports it directly; this script compiles the same file with the TypeScript compiler
 * into a self-contained classic script (`var RAPlateLayout = …`) and writes it as a string constant
 * to `src/map/plate-layout.browser.ts`, which the rich map embeds. No eval, no Function#toString,
 * no runtime dependency, and no network access.
 *
 *   node scripts/build-plate-layout.mjs          regenerate the browser bundle
 *   node scripts/build-plate-layout.mjs --check  fail if the committed bundle is stale (used by build)
 */

import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = resolve(SCRIPT_DIR, '..');
export const PLATE_LAYOUT_SOURCE = 'src/map/plate-layout.ts';
export const PLATE_LAYOUT_BUNDLE = 'src/map/plate-layout.browser.ts';

/** Returns the generated `plate-layout.browser.ts` contents for the current engine source. */
export function renderPlateLayoutBundle(rootDir = ROOT_DIR) {
  const source = readFileSync(join(rootDir, PLATE_LAYOUT_SOURCE), 'utf8').replace(/\r\n/g, '\n');
  const result = ts.transpileModule(source, {
    fileName: 'plate-layout.ts',
    reportDiagnostics: true,
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2019,
      removeComments: true,
      newLine: ts.NewLineKind.LineFeed,
    },
  });
  if (result.diagnostics && result.diagnostics.length > 0) {
    const messages = result.diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
    throw new Error(`Cannot compile ${PLATE_LAYOUT_SOURCE}:\n${messages.join('\n')}`);
  }
  if (/\brequire\s*\(/.test(result.outputText)) {
    throw new Error(`${PLATE_LAYOUT_SOURCE} must stay dependency-free (found require()).`);
  }
  const script = `var RAPlateLayout = (function () {\nvar exports = {};\n${result.outputText.trim()}\nreturn exports;\n})();\n`;
  if (/<\/script|<!--/i.test(script)) {
    throw new Error(`${PLATE_LAYOUT_SOURCE} compiles to text that cannot be inlined in a <script> element.`);
  }
  return [
    `// Generated by scripts/build-plate-layout.mjs from ${PLATE_LAYOUT_SOURCE}. Do not edit by hand;`,
    '// run `npm run build:plate-layout` after changing the engine.',
    '',
    '/** Browser build of the shared Briefing plate layout engine, inlined by the rich map template. */',
    `export const PLATE_LAYOUT_BROWSER_JS = ${JSON.stringify(script)};`,
    '',
  ].join('\n');
}

/** True when the committed bundle matches the engine source (ignoring CRLF checkouts on Windows). */
export function isPlateLayoutBundleCurrent(rootDir = ROOT_DIR) {
  const committed = readFileSync(join(rootDir, PLATE_LAYOUT_BUNDLE), 'utf8').replace(/\r\n/g, '\n');
  return committed === renderPlateLayoutBundle(rootDir);
}

const isMain =
  process.argv[1] !== undefined &&
  (() => {
    try {
      return realpathSync.native(resolve(process.argv[1])) === realpathSync.native(fileURLToPath(import.meta.url));
    } catch {
      return false;
    }
  })();

if (isMain) {
  try {
    if (process.argv.includes('--check')) {
      let current = false;
      try {
        current = isPlateLayoutBundleCurrent();
      } catch {
        current = false;
      }
      if (!current) {
        console.error(`error: ${PLATE_LAYOUT_BUNDLE} is stale; run \`npm run build:plate-layout\`.`);
        process.exit(1);
      }
    } else {
      writeFileSync(join(ROOT_DIR, PLATE_LAYOUT_BUNDLE), renderPlateLayoutBundle());
      console.log(`Wrote ${PLATE_LAYOUT_BUNDLE}`);
    }
  } catch (err) {
    console.error(`error: build-plate-layout failed: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  }
}
