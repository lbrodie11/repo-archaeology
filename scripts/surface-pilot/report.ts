export interface Verdict {
  correct: boolean;
  correctChecks: { scope: string; removal: boolean; signature: boolean; falsePositive: boolean }[];
  verdict: 'NOT CORRECT' | 'INSUFFICIENT' | 'PASS-WITNESS' | 'PASS-DESCRIBE' | 'STOP';
  steps: string[];
}

export function verdictOf(a: CorpusAResult[], pooled: CorpusAResult, b: CorpusBResult[]): Verdict {
  const checks = [pooled, ...a].map((r) => ({
    scope: r.repo,
    removal: r.removal.rate !== null && r.removal.rate >= THRESHOLDS.removalRecall,
    signature: r.signature.rate !== null && r.signature.rate >= THRESHOLDS.signatureRecall,
    falsePositive: r.falsePositive.rate !== null && r.falsePositive.rate <= THRESHOLDS.falsePositiveRate,
  }));
  const correct = a.length > 0 && checks.every((c) => c.removal && c.signature && c.falsePositive);
  const steps: string[] = [];
  if (!correct) {
    const failing = (key: 'removal' | 'signature' | 'falsePositive') => checks.filter((c) => !c[key]).map((c) => c.scope);
    const parts = [
      failing('removal').length ? `removal recall < 0.95 in ${failing('removal').join(', ')}` : '',
      failing('signature').length ? `signature/property recall < 0.90 in ${failing('signature').join(', ')}` : '',
      failing('falsePositive').length ? `false-positive rate > 0.02 in ${failing('falsePositive').join(', ')}` : '',
    ].filter(Boolean);
    steps.push(`CORRECT does not hold (${parts.join('; ') || 'no corpus-A data'}): NOT CORRECT. The rule stops here; corpus B and timing below are reported, not decisive.`);
    return { correct, correctChecks: checks, verdict: 'NOT CORRECT', steps };
  }
  steps.push('CORRECT holds pooled and in every repo.');
  if (b.length < 2 || b.some((r) => r.analyzed < THRESHOLDS.minAnalyzedPrs)) {
    steps.push(`Fewer than ${THRESHOLDS.minAnalyzedPrs} PRs analyzed in a corpus-B repo: INSUFFICIENT.`);
    return { correct, correctChecks: checks, verdict: 'INSUFFICIENT', steps };
  }
  const describe = b.some((r) => r.relevant.rate !== null && r.relevant.rate >= THRESHOLDS.relevantShare);
  const beyond = b.flatMap((r) => r.beyondCompiler);
  const followed = beyond.filter((f) => f.followUp.status === 'followed').length;
  const witness = describe && beyond.length >= THRESHOLDS.witnessFindings && followed / beyond.length >= THRESHOLDS.witnessFollowed;
  steps.push(`PASS-DESCRIBE condition (≥ 10% of PRs with a delta and ≥ 1 untouched consumer in at least one repo): ${describe ? 'holds' : 'does not hold'}.`);
  steps.push(`PASS-WITNESS condition (≥ 5 beyond-compiler findings, ≥ 80% followed within 7 days): ${beyond.length} findings, ${followed} followed: ${witness ? 'holds' : 'does not hold'}.`);
  const verdict = witness ? 'PASS-WITNESS' : describe ? 'PASS-DESCRIBE' : 'STOP';
  return { correct, correctChecks: checks, verdict, steps };
}

