/**
 * RA-18 report generator: computes every preregistered metric from the committed raw records
 * (docs/research/data/surface-pilot/) and renders the generated part of the Results section of
 * docs/research/surface-pilot.md, between the `surface-pilot:results` markers.
 *
 *   node --import tsx scripts/surface-pilot/report.ts --write   # results.json + the doc section
 *   node --import tsx scripts/surface-pilot/report.ts --check   # exit 1 if either is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

export const DATA_DIR = resolve(import.meta.dirname, '..', '..', 'docs', 'research', 'data', 'surface-pilot');
export const DOC = resolve(import.meta.dirname, '..', '..', 'docs', 'research', 'surface-pilot.md');
export const START = '<!-- surface-pilot:results:start (generated by scripts/surface-pilot/report.ts; do not edit) -->';
export const END = '<!-- surface-pilot:results:end -->';

export const THRESHOLDS = { removalRecall: 0.95, signatureRecall: 0.9, falsePositiveRate: 0.02, relevantShare: 0.1, witnessFindings: 5, witnessFollowed: 0.8, minAnalyzedPrs: 50 };

interface Use { file: string; name: string; status: string; reason?: string; via: string; through?: string[] }
interface ConsumerRecord { consumer: string; status: string; coverage: string; coverageReason?: string; uses: Use[] }
interface DeltaRecord { file: string; status: string; reason?: string; fileStatus: string; entries: { name: string; change: string; reasons?: string[] }[] }
interface Summary { changedSourceFiles: string[]; deltas: DeltaRecord[]; consumers: ConsumerRecord[]; skippedFiles: number; sourceFiles: number; parsedImporters: number }
interface MutationRecord { id: string; repo: string; class: 'positive' | 'negative'; kind: string; file: string; name: string; sha: string; oracleConsumers: string[]; ms: number; analysis: Summary }
interface Finding {
  consumer: string; file: string; name: string; via: string; through: string[]; coverage: string; coverageReason?: string;
  presentAtMerge: boolean; followUp: { status: 'followed' | 'not-followed' | 'censored'; commit?: string; hours?: number };
  typecheck?: { oracle: string; reason?: string; codes?: number[] };
}
interface PostHocItem { id: string; repo: string; kind: string; detected: boolean; category: string }
interface PrRecord { id: string; repo: string; base: string; merge: string; mergedAt: number; ms?: number; analysis?: Summary; findings?: Finding[]; error?: string }

export interface PilotData {
  a: Map<string, MutationRecord[]>;
  aMeta: Map<string, Record<string, unknown>>;
  b: Map<string, PrRecord[]>;
  bMeta: Map<string, Record<string, unknown>>;
  postHoc?: PostHocItem[];
}

const readJsonl = <T>(path: string): T[] => readFileSync(path, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as T);

export function loadData(dir = DATA_DIR): PilotData {
  const data: PilotData = { a: new Map(), aMeta: new Map(), b: new Map(), bMeta: new Map() };
  for (const [corpus, records, meta] of [['corpus-a', data.a, data.aMeta], ['corpus-b', data.b, data.bMeta]] as const) {
    const sub = join(dir, corpus);
    if (!existsSync(sub)) continue;
    for (const name of readdirSync(sub).sort()) {
      if (name.endsWith('.jsonl')) (records as Map<string, unknown[]>).set(name.slice(0, -6), readJsonl(join(sub, name)));
      if (name.endsWith('.meta.json')) meta.set(name.slice(0, -10), JSON.parse(readFileSync(join(sub, name), 'utf8')));
    }
  }
  const postHoc = join(dir, 'posthoc.json');
  if (existsSync(postHoc)) data.postHoc = (JSON.parse(readFileSync(postHoc, 'utf8')) as { items: PostHocItem[] }).items;
  return data;
}

