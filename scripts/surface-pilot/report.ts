export interface CorpusBResult {
  repo: string;
  prs: number;
  analyzed: number;
  errors: { id: string; error: string }[];
  anyDelta: Rate;
  /** PRs with at least one `removed` or `changed` entry (consumers are searched only for these). */
  affected: Rate;
  /** PRs where a changed source file's surface was `unknown` or `unavailable` on either side. */
  unknownSurface: Rate;
  relevant: Rate;
  relevantWithUncertain: Rate;
  findings: (Finding & { pr: string })[];
  beyondCompiler: (Finding & { pr: string })[];
  beyondFollowed: Rate;
  timing: { medianMs: number; p95Ms: number; maxMs: number; slowest: { id: string; ms: number; sourceFiles: number; parsedImporters: number }[] };
}

export function corpusB(repo: string, records: PrRecord[]): CorpusBResult {
  const analyzed = records.filter((r) => r.analysis && !r.error);
  const anyDelta = analyzed.filter((r) => r.analysis!.deltas.some((d) => d.entries.length > 0));
  const relevant = analyzed.filter((r) => r.analysis!.consumers.some((c) => c.status !== 'uncertain'));
  const relevantWithUncertain = analyzed.filter((r) => r.analysis!.consumers.length > 0);
  const findings = analyzed.flatMap((r) => (r.findings ?? []).map((f) => ({ pr: r.id, ...f })));
  const beyond = findings.filter((f) => f.coverage === 'not-typechecked');
  const times = analyzed.map((r) => r.ms!);
  const slowest = [...analyzed].sort((a, b) => b.ms! - a.ms! || (a.id < b.id ? -1 : 1)).slice(0, 5)
    .map((r) => ({ id: r.id, ms: r.ms!, sourceFiles: r.analysis!.sourceFiles, parsedImporters: r.analysis!.parsedImporters }));
  return {
    repo,
    prs: records.length,
    analyzed: analyzed.length,
    errors: records.filter((r) => r.error).map((r) => ({ id: r.id, error: r.error! })),
    anyDelta: rate(anyDelta.length, analyzed.length),
    affected: rate(analyzed.filter((r) => r.analysis!.deltas.some((d) => d.entries.some((e) => e.change !== 'added'))).length, analyzed.length),
    unknownSurface: rate(analyzed.filter((r) => r.analysis!.deltas.some((d) => d.status !== 'known')).length, analyzed.length),
    relevant: rate(relevant.length, analyzed.length),
    relevantWithUncertain: rate(relevantWithUncertain.length, analyzed.length),
    findings,
    beyondCompiler: beyond,
    beyondFollowed: rate(beyond.filter((f) => f.followUp.status === 'followed').length, beyond.length),
    timing: { medianMs: median(times), p95Ms: percentile(times, 0.95), maxMs: times.length ? Math.max(...times) : 0, slowest },
  };
}

export function median(values: number[]): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[mid]! : Math.round((sorted[mid - 1]! + sorted[mid]!) / 2);
}

/** Nearest-rank percentile. */
export function percentile(values: number[], p: number): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.max(0, Math.ceil(p * sorted.length) - 1)]!;
}

