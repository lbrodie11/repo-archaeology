export interface PostHoc {
  /** repo → category → detected / total positives. */
  table: Record<string, Record<string, Rate>>;
  /** Positives whose verified consumer names the export directly or through explicit re-exports. */
  syntacticallyReachable: Rate;
}

export interface PilotResults {
  postHoc?: PostHoc;
  corpusA: CorpusAResult[];
  pooled: CorpusAResult;
  corpusB: CorpusBResult[];
  verdict: Verdict;
  meta: { a: Record<string, unknown>; b: Record<string, unknown> };
}

export function computeResults(data: PilotData): PilotResults {
  const a = [...data.a].map(([repo, records]) => corpusA(repo, records));
  const pooled = pool(a);
  const b = [...data.b].map(([repo, records]) => corpusB(repo, records));
  const results: PilotResults = { corpusA: a, pooled, corpusB: b, verdict: verdictOf(a, pooled, b), meta: { a: Object.fromEntries(data.aMeta), b: Object.fromEntries(data.bMeta) } };
  if (data.postHoc) results.postHoc = postHocOf(data.postHoc);
  return results;
}

export const POSTHOC_CATEGORIES = ['named', 'named-via-barrel', 'only-via-export-star', 'only-namespace', 'no-import-found'];

function postHocOf(items: PostHocItem[]): PostHoc {
  const table: Record<string, Record<string, Rate>> = {};
  for (const item of items) {
    for (const repo of ['pooled', item.repo]) {
      const row = (table[repo] ??= {});
      const current = row[item.category] ?? rate(0, 0);
      row[item.category] = rate(current.k + (item.detected ? 1 : 0), current.n + 1);
    }
  }
  const reachable = items.filter((i) => i.category === 'named' || i.category === 'named-via-barrel');
  return { table, syntacticallyReachable: rate(reachable.filter((i) => i.detected).length, reachable.length) };
}

const fmt = (r: Rate) => (r.rate === null ? 'n/a (0/0)' : `${r.rate.toFixed(3)} (${r.k}/${r.n})`);
const mark = (ok: boolean) => (ok ? 'yes' : '**no**');
const short = (sha: string) => sha.slice(0, 7);

export function renderMarkdown(results: PilotResults): string {
  const out: string[] = [];
  const { corpusA: a, pooled, corpusB: b, verdict } = results;
  out.push(`**Verdict (mechanical, §6): ${verdict.verdict}.**`, '');
  for (const step of verdict.steps) out.push(`- ${step}`);
  out.push('', '### R1 · Corpus A: seeded mutations', '');
  out.push('| Scope | Removal recall (≥ 0.95) | Signature/property recall (≥ 0.90) | False-positive rate (≤ 0.02) | Uncertain share | Oracle-consumer recall (not decisive) |');
  out.push('|---|---|---|---|---|---|');
  for (const r of [pooled, ...a]) {
    const check = verdict.correctChecks.find((c) => c.scope === r.repo)!;
    out.push(`| ${r.repo} | ${fmt(r.removal)} ${mark(check.removal)} | ${fmt(r.signature)} ${mark(check.signature)} | ${fmt(r.falsePositive)} ${mark(check.falsePositive)} | ${fmt(r.uncertainShare)} | ${fmt(r.oracleConsumerRecall)} |`);
  }
  out.push('', 'By kind (positives: detected; negative controls: false positives):', '');
  const kinds = Object.keys(pooled.byKind).sort();
  out.push(`| Kind | ${['pooled', ...a.map((r) => r.repo)].join(' | ')} |`, `|---|${['pooled', ...a].map(() => '---').join('|')}|`);
  for (const kind of kinds) out.push(`| ${kind} | ${[pooled, ...a].map((r) => (r.byKind[kind] ? fmt(r.byKind[kind]!) : '–')).join(' | ')} |`);
  out.push('', 'Generation (from `corpus-a/<repo>.meta.json`):', '');
  for (const [repo, meta] of Object.entries(results.meta.a)) {
    const m = meta as { pin: string; eligibleFiles: number; shortfalls: Record<string, number> };
    const shortfalls = Object.entries(m.shortfalls ?? {});
    out.push(`- ${repo} @ \`${short(m.pin)}\`: ${m.eligibleFiles} eligible files; quota shortfalls ${shortfalls.length ? shortfalls.map(([k, v]) => `${k} −${v}`).join(', ') : 'none'}.`);
  }
  out.push('', '**Failure classes** (every missed positive and every false positive):', '');
  if (Object.keys(pooled.failureClasses).length === 0) out.push('None.');
  else {
    out.push('| Class | Count |', '|---|---|');
    for (const [cls, n] of Object.entries(pooled.failureClasses)) out.push(`| ${cls} | ${n} |`);
  }
  out.push('', '### R2 · Corpus B: real PRs', '');
  out.push('| Repo | PRs | Analyzed | Any surface delta | A `removed` or `changed` entry | Delta + ≥ 1 untouched consumer (decisive, ≥ 10%) | … counting `uncertain` consumers too | A changed file with an `unknown` surface | `uses-removed-name` findings | Beyond-compiler | Followed within 7 days |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of b) {
    out.push(`| ${r.repo} | ${r.prs} | ${r.analyzed} | ${fmt(r.anyDelta)} | ${fmt(r.affected)} | ${fmt(r.relevant)} | ${fmt(r.relevantWithUncertain)} | ${fmt(r.unknownSurface)} | ${r.findings.length} | ${r.beyondCompiler.length} | ${fmt(r.beyondFollowed)} |`);
  }
  for (const r of b) if (r.errors.length) out.push('', `${r.repo}: ${r.errors.length} PRs not analyzed: ${r.errors.map((e) => `${e.id} (${e.error})`).join('; ')}.`);
  out.push('', '**Every `uses-removed-name` finding** (oracles: still present at merge; consumer changed within 7 days; type-check of `typechecked` consumers):', '');
  const all = b.flatMap((r) => r.findings.map((f) => ({ repo: r.repo, ...f })));
  if (all.length === 0) out.push('None.');
  else {
    out.push('| Repo | PR | Consumer | Removed from | Name | Coverage | Present at merge | Follow-up (7 days) | Type-check oracle |', '|---|---|---|---|---|---|---|---|---|');
    for (const f of all) {
      const follow = f.followUp.status === 'followed' ? `followed (\`${short(f.followUp.commit!)}\`, ${f.followUp.hours} h)` : f.followUp.status;
      const tc = f.typecheck ? `${f.typecheck.oracle}${f.typecheck.codes ? ` (TS${f.typecheck.codes.join(', TS')})` : ''}${f.typecheck.reason ? `: ${f.typecheck.reason}` : ''}` : '– (not typechecked)';
      out.push(`| ${f.repo} | ${f.pr} | \`${f.consumer}\` | \`${f.file}\` | \`${f.name}\` | ${f.coverage} | ${f.presentAtMerge ? 'yes' : 'no'} | ${follow} | ${tc} |`);
    }
  }
  out.push('', '### R3 · Time per PR', '');
  out.push('| Repo | Median (hono budget ≤ 2 s) | p95 (hono budget ≤ 10 s) | Max | Slowest PRs (ms, source files, importers parsed) |', '|---|---|---|---|---|');
  for (const r of b) {
    const within = r.repo === 'hono' ? ` ${r.timing.medianMs <= 2000 && r.timing.p95Ms <= 10000 ? '(within budget)' : '(**over budget**)'}` : '';
    out.push(`| ${r.repo} | ${r.timing.medianMs} ms${within} | ${r.timing.p95Ms} ms | ${r.timing.maxMs} ms | ${r.timing.slowest.map((s) => `${s.id} ${s.ms} ms, ${s.sourceFiles}, ${s.parsedImporters}`).join('; ')} |`);
  }
  const machine = Object.values(results.meta.b)[0] as { machine?: { cpu: string; cpus: number; memoryGb: number; node: string; platform: string } } | undefined;
  if (machine?.machine) {
    const m = machine.machine;
    out.push('', `Measured on ${m.cpu} (${m.cpus} cores, ${m.memoryGb} GB), ${m.platform}, Node ${m.node}, wall clock per PR with fresh resolver and caches, TypeScript already loaded. Not a CI runner.`);
  }
  if (results.postHoc) {
    const { table, syntacticallyReachable } = results.postHoc;
    out.push('', '### R4 · Post-hoc: how the oracle\'s consumers really reach each positive (NOT part of the rule; cannot change the verdict)', '');
    out.push('Written after the R1 results by `scripts/surface-pilot/posthoc.ts` (`posthoc.json`). For every positive, the oracle\'s ground-truth consumers are re-read with TypeScript\'s own module resolution (not `src/surface/`) and the positive gets the strongest way any of them reaches the mutated export. Cells: detected / positives.', '');
    const repos = Object.keys(table).sort((x, y) => (x === 'pooled' ? -1 : y === 'pooled' ? 1 : x < y ? -1 : 1));
    out.push(`| How a verified consumer reaches the export | ${repos.join(' | ')} |`, `|---|${repos.map(() => '---').join('|')}|`);
    for (const category of POSTHOC_CATEGORIES) out.push(`| ${category} | ${repos.map((r) => (table[r]![category] ? fmt(table[r]![category]!) : '–')).join(' | ')} |`);
    out.push('', `Detection where a verified consumer names the export directly or through explicit re-exports (\`named\` + \`named-via-barrel\`): ${fmt(syntacticallyReachable)}.`);
  }
  return out.join('\n');
}

export function replaceSection(doc: string, section: string): string {
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error('results markers not found in surface-pilot.md');
  return `${doc.slice(0, start + START.length)}\n\n${section}\n\n${doc.slice(end)}`;
}

export function resultsJson(results: PilotResults): string {
  return `${JSON.stringify(results, null, 2)}\n`;
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { write: { type: 'boolean' }, check: { type: 'boolean' } } });
  const results = computeResults(loadData());
  const doc = readFileSync(DOC, 'utf8');
  const nextDoc = replaceSection(doc, renderMarkdown(results));
  const json = resultsJson(results);
  const jsonPath = join(DATA_DIR, 'results.json');
  if (values.write) {
    writeFileSync(DOC, nextDoc);
    writeFileSync(jsonPath, json);
    process.stdout.write(`verdict: ${results.verdict.verdict}\n`);
  } else if (values.check) {
    const stale = [doc !== nextDoc ? DOC : '', !existsSync(jsonPath) || readFileSync(jsonPath, 'utf8') !== json ? jsonPath : ''].filter(Boolean);
    if (stale.length) {
      process.stderr.write(`stale: ${stale.join(', ')}\n`);
      process.exit(1);
    }
  } else {
    process.stdout.write(`${renderMarkdown(results)}\n`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main();
}
