export interface ItemOutcome { id: string; kind: string; ok: boolean; failure?: string }

/** Detection (positives) and false positives (negatives), exactly as preregistered in §4. */
export function judge(record: MutationRecord): ItemOutcome {
  const { analysis } = record;
  const delta = analysis.deltas.find((d) => d.file === record.file);
  const entry = delta?.entries.find((e) => e.name === record.name);
  const uses = analysis.consumers.flatMap((c) => c.uses.filter((u) => u.file === record.file && u.name === record.name).map((u) => ({ ...u, consumer: c.consumer })));
  if (record.class === 'positive') {
    const wantChange = record.kind === 'remove-export' ? 'removed' : 'changed';
    const wantReason = record.kind === 'add-required-param' ? 'required-params-increased' : record.kind === 'add-required-prop' ? 'required-props-added' : undefined;
    const wantStatus = record.kind === 'remove-export' ? 'uses-removed-name' : 'uses-changed-export';
    if (!delta || delta.status !== 'known') return { id: record.id, kind: record.kind, ok: false, failure: `delta-unknown: ${delta?.reason ?? 'file not analyzed'}` };
    if (!entry) return { id: record.id, kind: record.kind, ok: false, failure: 'delta-missing' };
    if (entry.change !== wantChange || (wantReason && !entry.reasons?.includes(wantReason))) {
      return { id: record.id, kind: record.kind, ok: false, failure: `delta-wrong: ${entry.change}${entry.reasons ? ` ${entry.reasons.join('+')}` : ''}` };
    }
    if (uses.some((u) => u.status === wantStatus)) return { id: record.id, kind: record.kind, ok: true };
    if (uses.length === 0) return { id: record.id, kind: record.kind, ok: false, failure: 'no-consumer-found' };
    const reasons = [...new Set(uses.map((u) => u.reason ?? u.status))].sort();
    return { id: record.id, kind: record.kind, ok: false, failure: `only-uncertain: ${reasons.join('+')}` };
  }
  const problems: string[] = [];
  for (const d of analysis.deltas) {
    for (const e of d.entries) {
      if (e.change === 'removed' || e.change === 'changed') problems.push(`delta-${e.change}`);
    }
  }
  if (analysis.consumers.some((c) => c.status !== 'uncertain')) problems.push('certain-consumer');
  if (record.kind === 'add-export') {
    const all = analysis.deltas.flatMap((d) => d.entries);
    if (!(all.length === 1 && all[0]!.change === 'added' && all[0]!.name === record.name)) problems.push(`add-export-not-exactly-added (${all.map((e) => `${e.name}:${e.change}`).join(', ') || 'no entries'}${delta?.status === 'unknown' ? `; unknown: ${delta.reason}` : ''})`);
  }
  return problems.length === 0 ? { id: record.id, kind: record.kind, ok: true } : { id: record.id, kind: record.kind, ok: false, failure: [...new Set(problems)].join('; ') };
}

interface Rate { n: number; k: number; rate: number | null }
const rate = (k: number, n: number): Rate => ({ n, k, rate: n === 0 ? null : k / n });

export interface CorpusAResult {
  repo: string;
  removal: Rate;
  signature: Rate;
  byKind: Record<string, Rate>;
  falsePositive: Rate;
  uncertainShare: Rate;
  oracleConsumerRecall: Rate;
  failures: { id: string; kind: string; file: string; name: string; failure: string }[];
  failureClasses: Record<string, number>;
  medianMs: number;
}

export function corpusA(repo: string, records: MutationRecord[]): CorpusAResult {
  const outcomes = records.map((r) => ({ r, o: judge(r) }));
  const positives = outcomes.filter(({ r }) => r.class === 'positive');
  const negatives = outcomes.filter(({ r }) => r.class === 'negative');
  const removal = positives.filter(({ r }) => r.kind === 'remove-export');
  const signature = positives.filter(({ r }) => r.kind !== 'remove-export');
  const byKind: Record<string, Rate> = {};
  for (const { r, o } of outcomes) {
    const current = byKind[r.kind] ?? rate(0, 0);
    // Positives: detected; negatives: false positives.
    const hit = r.class === 'positive' ? o.ok : !o.ok;
    byKind[r.kind] = rate(current.k + (hit ? 1 : 0), current.n + 1);
  }
  let consumers = 0;
  let uncertain = 0;
  let oracleTotal = 0;
  let oracleFound = 0;
  for (const { r } of positives) {
    consumers += r.analysis.consumers.length;
    uncertain += r.analysis.consumers.filter((c) => c.status === 'uncertain').length;
    for (const consumer of r.oracleConsumers) {
      oracleTotal++;
      const found = r.analysis.consumers.find((c) => c.consumer === consumer);
      if (found?.uses.some((u) => u.file === r.file && u.name === r.name && u.status !== 'uncertain')) oracleFound++;
    }
  }
  const failures = outcomes.filter(({ o }) => !o.ok).map(({ r, o }) => ({ id: r.id, kind: r.kind, file: r.file, name: r.name, failure: o.failure! }));
  const failureClasses: Record<string, number> = {};
  for (const f of failures) {
    const cls = `${f.kind}: ${f.failure.replace(/ \(.*\)$/, '')}`;
    failureClasses[cls] = (failureClasses[cls] ?? 0) + 1;
  }
  return {
    repo,
    removal: rate(removal.filter(({ o }) => o.ok).length, removal.length),
    signature: rate(signature.filter(({ o }) => o.ok).length, signature.length),
    byKind,
    falsePositive: rate(negatives.filter(({ o }) => !o.ok).length, negatives.length),
    uncertainShare: rate(uncertain, consumers),
    oracleConsumerRecall: rate(oracleFound, oracleTotal),
    failures,
    failureClasses: Object.fromEntries(Object.entries(failureClasses).sort(([a], [b]) => (a < b ? -1 : 1))),
    medianMs: median(records.map((r) => r.ms)),
  };
}

function pool(results: CorpusAResult[]): CorpusAResult {
  const sum = (pick: (r: CorpusAResult) => Rate) => rate(results.reduce((s, r) => s + pick(r).k, 0), results.reduce((s, r) => s + pick(r).n, 0));
  const byKind: Record<string, Rate> = {};
  for (const r of results) for (const [k, v] of Object.entries(r.byKind)) byKind[k] = rate((byKind[k]?.k ?? 0) + v.k, (byKind[k]?.n ?? 0) + v.n);
  const failureClasses: Record<string, number> = {};
  for (const r of results) for (const [k, v] of Object.entries(r.failureClasses)) failureClasses[k] = (failureClasses[k] ?? 0) + v;
  return {
    repo: 'pooled',
    removal: sum((r) => r.removal),
    signature: sum((r) => r.signature),
    byKind,
    falsePositive: sum((r) => r.falsePositive),
    uncertainShare: sum((r) => r.uncertainShare),
    oracleConsumerRecall: sum((r) => r.oracleConsumerRecall),
    failures: results.flatMap((r) => r.failures),
    failureClasses: Object.fromEntries(Object.entries(failureClasses).sort(([a], [b]) => (a < b ? -1 : 1))),
    medianMs: Math.round(median(results.map((r) => r.medianMs))),
  };
}

